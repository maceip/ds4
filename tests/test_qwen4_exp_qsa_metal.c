#define QSA_INDEX_HEADS 4u
#define QSA_INDEX_DIM 128u
#define QSA_BLOCK 4u
#define QSA_BLOCKS 8u
#define QSA_INDEX_TOKENS (QSA_BLOCKS * QSA_BLOCK)
#define QSA_HEADS 24u
#define QSA_KV_HEADS 2u
#define QSA_HEAD_DIM 256u
